function soundCloudFeedUrl(sermon) {
  if (sermon.audioUrl) return sermon.audioUrl;
  const slug = String(sermon.url || "").split("/").filter(Boolean).pop();
  return sermon.id && slug
    ? `https://feeds.soundcloud.com/stream/${sermon.id}-familiekirken-mandal-${slug}.mp3`
    : "";
}

function parseNorwegianDate(date) {
  const match = String(date || "").match(/^(\d{1,2})\.(\d{1,2})\.(\d{4})$/);
  if (!match) return null;
  return new Date(Number(match[3]), Number(match[2]) - 1, Number(match[1]));
}

function sortSermonsNewest(list) {
  return [...list].sort((a, b) => {
    const aTime = Date.parse(a.publishedAt || "") || parseNorwegianDate(a.date)?.getTime() || 0;
    const bTime = Date.parse(b.publishedAt || "") || parseNorwegianDate(b.date)?.getTime() || 0;
    return bTime - aTime;
  });
}

function prepareSermon(sermon) {
  const sermonDate = parseNorwegianDate(sermon.date);
  return {
    ...sermon,
    year: sermonDate ? String(sermonDate.getFullYear()) : sermon.year,
    audioUrl: soundCloudFeedUrl(sermon)
  };
}

function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function formatDuration(ms) {
  const total = Math.round((ms || 0) / 1000);
  return `${Math.floor(total / 60)}:${String(total % 60).padStart(2, "0")}`;
}

function parseSoundCloudTitle(rawTitle, publishedAt) {
  const raw = String(rawTitle || "").replace(/\s+/g, " ").trim();
  const match = raw.match(/^(.*?)\s+(\d{1,2}\.\d{1,2}\.\d{4})\s+-\s+(.*)$/);
  if (match) {
    return { speaker: match[1].trim(), date: match[2].trim(), title: match[3].trim() };
  }
  const date = publishedAt ? new Date(publishedAt).toLocaleDateString("no-NO") : "SoundCloud";
  return { speaker: "Familiekirken-Mandal", date, title: raw };
}

function normalizeTrack(track) {
  const publishedAt = track.display_date || track.created_at || "";
  const parsed = parseSoundCloudTitle(track.title, publishedAt);
  const progressive = track.media?.transcodings?.find((item) => item.format?.protocol === "progressive");
  const streamApi = progressive?.url && track.track_authorization
    ? `${progressive.url}?client_id=${SOUNDCLOUD_CLIENT_ID}&track_authorization=${track.track_authorization}`
    : "";
  const publishedDate = publishedAt ? new Date(publishedAt) : null;

  return {
    id: track.id,
    title: parsed.title,
    speaker: parsed.speaker,
    date: parsed.date,
    year: publishedDate ? String(publishedDate.getFullYear()) : "Ukjent",
    publishedAt,
    duration: formatDuration(track.duration),
    url: track.permalink_url,
    streamApi,
    audioUrl: soundCloudFeedUrl({ id: track.id, url: track.permalink_url }),
    plays: track.playback_count || 0,
    description: track.description || ""
  };
}

function normalizeRssItem(item) {
  const id = Number(String(item.guid || "").match(/tracks\/(\d+)/)?.[1]);
  const publishedAt = item.pubDate ? new Date(item.pubDate.replace(" ", "T")).toISOString() : "";
  const parsed = parseSoundCloudTitle(item.title, publishedAt);
  const durationSeconds = Number(item.enclosure?.duration || 0);
  const sermonDate = parseNorwegianDate(parsed.date);

  return {
    id,
    title: parsed.title,
    speaker: parsed.speaker,
    date: parsed.date,
    year: sermonDate ? String(sermonDate.getFullYear()) : (publishedAt ? String(new Date(publishedAt).getFullYear()) : "Ukjent"),
    publishedAt,
    duration: durationSeconds ? formatDuration(durationSeconds * 1000) : "",
    url: item.link,
    streamApi: "",
    audioUrl: item.enclosure?.link || soundCloudFeedUrl({ id, url: item.link }),
    plays: 0,
    description: item.description || ""
  };
}

function mergeSermons(liveItems, fallbackItems) {
  const byId = new Map();
  [...liveItems, ...fallbackItems].forEach((sermon) => {
    if (!sermon.id) return;
    byId.set(sermon.id, prepareSermon({ ...byId.get(sermon.id), ...sermon }));
  });
  return sortSermonsNewest([...byId.values()]);
}

async function refreshFromSoundCloud() {
  try {
    const response = await fetch(SOUNDCLOUD_RSS_JSON_URL, { cache: "no-store" });
    if (!response.ok) throw new Error(`SoundCloud svarte ${response.status}`);
    const data = await response.json();
    const liveItems = (data.items || []).map(normalizeRssItem);
    sermons = mergeSermons(liveItems, fallbackSermons);
    playerStatus.textContent = `Arkivet er oppdatert fra SoundCloud-feeden. Nyeste episoder ligger øverst.`;
  } catch (error) {
    console.warn("Kunne ikke hente live fra SoundCloud-feeden, bruker fallback-arkiv.", error);
    sermons = sortSermonsNewest(fallbackSermons.map(prepareSermon));
    playerStatus.textContent = "Viser sist synkroniserte arkiv. Nyeste episoder ligger øverst.";
  }

  updateLatestFeature();
  createYearFilters();
  renderSermons();
  primePlayer(sermons[0]);
}

function updateLatestFeature() {
  const latest = sermons[0];
  if (!latest) return;
  if (latestTitle) latestTitle.textContent = latest.title;
  if (latestText) latestText.textContent = "Nyeste episode hentet fra SoundCloud-profilen til Familiekirken-Mandal.";
  if (latestDate) latestDate.textContent = latest.date;
  if (latestSpeaker) latestSpeaker.textContent = latest.speaker;
  if (latestDuration) latestDuration.textContent = latest.duration;
}

function createYearFilters() {
  const years = [...new Set(sermons.map((sermon) => sermon.year))]
    .filter(Boolean)
    .sort((a, b) => Number(b) - Number(a));

  filters.innerHTML = ["alle", ...years].map((year, index) => `
    <button class="${index === 0 ? "active" : ""}" type="button" data-sermon-year="${year}">${year === "alle" ? "Alle" : year}</button>
  `).join("");

  currentYear = "alle";
  filters.querySelectorAll("[data-sermon-year]").forEach((button) => {
    button.addEventListener("click", () => {
      filters.querySelectorAll("button").forEach((item) => item.classList.remove("active"));
      button.classList.add("active");
      currentYear = button.dataset.sermonYear;
      renderSermons();
    });
  });
}

function renderSermons() {
  const query = search.value.trim().toLowerCase();
  const visible = sermons.filter((sermon) => {
    const matchesYear = currentYear === "alle" || sermon.year === currentYear;
    const haystack = `${sermon.title} ${sermon.speaker} ${sermon.date} ${sermon.year}`.toLowerCase();
    return matchesYear && haystack.includes(query);
  });

  list.innerHTML = visible.map((sermon) => {
    return `
    <article class="sermon-row">
      <div>
        <span>${escapeHtml(sermon.date)} · ${escapeHtml(sermon.duration)}</span>
        <h3>${escapeHtml(sermon.title)}</h3>
        <p>${escapeHtml(sermon.speaker)}</p>
      </div>
      <div class="sermon-row-side">
        <strong>${escapeHtml(sermon.year)}</strong>
        <button type="button" data-sermon-id="${escapeHtml(sermon.id)}">Lytt her</button>
        <a href="${escapeHtml(sermon.url)}" target="_blank" rel="noreferrer">SoundCloud</a>
      </div>
    </article>`;
  }).join("");

  if (!visible.length) {
    list.innerHTML = '<article class="sermon-row"><div><h3>Ingen treff</h3><p>Prøv et annet søkeord eller år.</p></div></article>';
  }

}

async function playTrack(sermon) {
  const audioUrl = soundCloudFeedUrl(sermon);
  playerTitle.textContent = sermon.title;
  playerMeta.textContent = `${sermon.speaker} · ${sermon.date} · ${sermon.duration}`;
  playerStatus.textContent = "Henter lyd fra SoundCloud-feeden...";
  inlinePlayer.scrollIntoView({ behavior: "smooth", block: "center" });

  try {
    if (!audioUrl) throw new Error("Mangler lydlenke");
    audio.src = audioUrl;
    audio.load();
    await audio.play();
    playerStatus.textContent = "Spiller av på siden.";
  } catch (error) {
    console.error(error);
    playerStatus.innerHTML = `Kunne ikke hente lydfilen her. <a href="${sermon.url}" target="_blank" rel="noreferrer">Åpne i SoundCloud</a>`;
  }
}

function primePlayer(sermon) {
  if (!sermon) return;
  playerTitle.textContent = sermon.title;
  playerMeta.textContent = `${sermon.speaker} · ${sermon.date} · ${sermon.duration}`;
}

